# --- Run the probe, once per requested variant -----------------------
for variant in "${VARIANTS[@]}"; do
	VARIANT_OUT_DIR="$OUT_DIR/out-$variant"
	mkdir -p "$VARIANT_OUT_DIR"
	# The probe container runs as UID 65532, not this script's own user; the
	# output directory must be writable by it regardless of who invokes this
	# script.
	chmod 0777 "$VARIANT_OUT_DIR"

	EXTRA_PROBE_ARGS=()
	case "$variant" in
	full)
		CAP_ADD_ARGS=(--cap-add SYS_PTRACE --cap-add DAC_READ_SEARCH --cap-add BPF --cap-add PERFMON)
		;;
	no-bpf-caps)
		# Exercises the "BPF/PERFMON not granted" path: the setcap'd
		# binary's file capability is +p only (see the Dockerfile), so
		# exec must still succeed even though the container's bounding
		# set lacks two of the four named capabilities; the probe must
		# then report eBPF unavailable rather than failing outright.
		CAP_ADD_ARGS=(--cap-add SYS_PTRACE --cap-add DAC_READ_SEARCH)
		;;
	simulate-attach-failure)
		CAP_ADD_ARGS=(--cap-add SYS_PTRACE --cap-add DAC_READ_SEARCH --cap-add BPF --cap-add PERFMON)
		EXTRA_PROBE_ARGS=(--simulate-ebpf-attach-failure)
		;;
	esac

	echo "run-probe.sh: running kestrelynx sensor --probe (variant: $variant)" >&2
	# Flags mirror docker-compose.sensor-probe.yml's service definition
	# exactly (pid:host -> --pid host, cgroup:host -> --cgroupns host, and
	# so on) aside from the per-variant cap_add list above; see that file
	# for the rationale behind each one.
	ledger_run_container "$LEDGER" "$RUN_ID" "kl-sensor-probe-$RUN_ID-$variant" --rm \
		--entrypoint kestrelynx-sensor \
		--pid host \
		--cgroupns host \
		--network none \
		--cap-drop ALL \
		"${CAP_ADD_ARGS[@]}" \
		--security-opt "seccomp=$SECCOMP_PROFILE" \
		--user 65532:65532 \
		--read-only \
		-v "$VARIANT_OUT_DIR:/out" \
		-v "$IN_DIR:/inspect:ro" \
		"$SENSOR_IMAGE" \
		sensor --probe \
		--out /out/probe-report.json \
		--inspect-json /inspect/inspect.json \
		--listen-events 8s \
		--run-id "$RUN_ID" \
		"${EXTRA_PROBE_ARGS[@]}" \
		"${TARGET_ARGS[@]}" 2>&1 | tee "$OUT_DIR/probe-run-$variant.log" >&2

	READABLE="$OUT_DIR/probe-report-$variant.json"
	if [ -f "$VARIANT_OUT_DIR/probe-report.json" ]; then
		# Same reasoning as the fcap-check read-back above: the report is
		# UID 65532 mode 0600, unreadable by this script's own user.
		ledger_run_container "$LEDGER" "$RUN_ID" "kl-sensor-read-$RUN_ID-$variant" --rm \
			--entrypoint cat -v "$VARIANT_OUT_DIR:/out" "$SENSOR_IMAGE" /out/probe-report.json >"$READABLE" 2>/dev/null || true
	fi
	if [ -s "$READABLE" ]; then
		echo "run-probe.sh: probe report (variant $variant) at $READABLE" >&2
		echo "run-probe.sh: summary (variant $variant):" >&2
		python3 "$OUT_DIR/summarize.py" "$READABLE" >&2
	else
		echo "run-probe.sh: WARNING: no readable probe report for variant $variant; see $OUT_DIR/probe-run-$variant.log" >&2
	fi
done

echo "run-probe.sh: done. Collected files:" >&2
echo "  $PREFLIGHT" >&2
echo "  $OUT_DIR/build.log" >&2
echo "  $FCAP_CHECK" >&2
echo "  $IN_DIR/inspect.json" >&2
echo "  $LEDGER" >&2
for variant in "${VARIANTS[@]}"; do
	echo "  $OUT_DIR/probe-run-$variant.log" >&2
	echo "  $OUT_DIR/probe-report-$variant.json (if produced)" >&2
done
