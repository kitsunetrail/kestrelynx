func cargoFixture(t *testing.T, name string) string {
	t.Helper()
	b, err := os.ReadFile("testdata/cargo/" + name)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

const (
	cksumA = "1111111111111111111111111111111111111111111111111111111111111111"
	cksumB = "2222222222222222222222222222222222222222222222222222222222222222"
)

// cargoLockText writes a Cargo.lock of the given version from packages, each
// written as a [[package]] block by the caller.
func cargoLockText(version int, blocks ...string) string {
	var b strings.Builder
	b.WriteString("# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\n")
	b.WriteString("version = " + string(rune('0'+version)) + "\n")
	for _, bl := range blocks {
		b.WriteString("\n[[package]]\n" + bl)
	}
	return b.String()
}

func cratesBlock(name, version, checksum string, deps ...string) string {
	s := "name = \"" + name + "\"\nversion = \"" + version + "\"\nsource = \"" + cratesIOSource + "\"\nchecksum = \"" + checksum + "\"\n"
	return s + depsLines(deps)
}

func ownBlock(name, version string, deps ...string) string {
	return "name = \"" + name + "\"\nversion = \"" + version + "\"\n" + depsLines(deps)
}

func depsLines(deps []string) string {
	if len(deps) == 0 {
		return ""
	}
	s := "dependencies = [\n"
	for _, d := range deps {
		s += " \"" + d + "\",\n"
	}
	return s + "]\n"
}

func TestParseCargoLock_RealFiles(t *testing.T) {
	// The files cargo 1.100.0 wrote: a direct dependency that brings in a
	// crate per platform, a workspace of two packages, and a version 3 file
	// with two versions of one crate under two names.
	l, err := parseCargoLock([]byte(cargoFixture(t, "exp1.Cargo.lock")))
	if err != nil {
		t.Fatal(err)
	}
	if l.version != 4 || len(l.crates) != 12 {
		t.Fatalf("exp1: version %d, %d crates", l.version, len(l.crates))
	}
	tokio := l.find("tokio", "1.23.1", cratesIOSource)
	if tokio < 0 || len(l.crates[tokio].deps) != 3 {
		t.Fatalf("tokio = %d %+v", tokio, l.crates[tokio])
	}
	if own := l.find("exp1", "0.1.0", ""); own < 0 || l.crates[own].registry() || !l.reach(own)[tokio] {
		t.Errorf("exp1 does not lead to tokio")
	}
	if got := l.reach(l.find("windows-sys", "0.42.0", cratesIOSource)); len(got) != 8 {
		t.Errorf("windows-sys reaches %d crates", len(got))
	}

	l, err = parseCargoLock([]byte(cargoFixture(t, "exp3.Cargo.lock")))
	if err != nil {
		t.Fatal(err)
	}
	a, b := l.find("a", "0.1.0", ""), l.find("b", "0.1.0", "")
	if a < 0 || b < 0 || len(l.crates[a].deps) != 2 || !l.reach(a)[l.find("smallvec", "1.6.0", cratesIOSource)] || l.reach(b)[a] {
		t.Errorf("exp3 edges: a %d b %d", a, b)
	}

	l, err = parseCargoLock([]byte(cargoFixture(t, "exp4.Cargo.lock")))
	if err != nil {
		t.Fatal(err)
	}
	if l.version != 3 {
		t.Errorf("exp4 version = %d", l.version)
	}
	if v := l.versionsOf("syn"); strings.Join(v, ",") != "1.0.109,2.0.50" {
		t.Errorf("syn versions = %v", v)
	}
	// The package that depends on both versions names each with its version.
	var named []string
	for _, i := range l.byName["exp4"] {
		for _, d := range l.crates[i].deps {
			if l.crates[d].name == "syn" {
				named = append(named, l.crates[d].version)
			}
		}
	}
	if strings.Join(named, ",") != "1.0.109,2.0.50" {
		t.Errorf("exp4 depends on syn %v", named)
	}
}

func TestParseCargoLock_DependencyForms(t *testing.T) {
	// "name", "name version" and "name version (source)" each name one crate.
	text := cargoLockText(4,
		ownBlock("app", "0.1.0", "dup 1.0.0", "dup 2.0.0 (registry+https://github.com/rust-lang/crates.io-index)", "solo"),
		cratesBlock("dup", "1.0.0", cksumA),
		cratesBlock("dup", "2.0.0", cksumB),
		cratesBlock("solo", "0.3.1", cksumA),
	)
	l, err := parseCargoLock([]byte(text))
	if err != nil {
		t.Fatal(err)
	}
	app := l.find("app", "0.1.0", "")
	want := []string{"dup@1.0.0", "dup@2.0.0", "solo@0.3.1"}
	for i, d := range l.crates[app].deps {
		if got := l.crates[d].id(); got != want[i] {
			t.Errorf("dependency %d = %s, want %s", i, got, want[i])
		}
	}
}

func TestParseCargoLock_Refusals(t *testing.T) {
	good := cratesBlock("tokio", "1.18.0", cksumA)
	unsupportedCase := func(reason Reason) func(error) bool {
		return func(err error) bool {
			var ue *UnsupportedError
			return errors.As(err, &ue) && ue.Reason == reason
		}
	}
	plain := func(err error) bool {
		var ue *UnsupportedError
		return err != nil && !errors.As(err, &ue)
	}
	for name, c := range map[string]struct {
		text string
		ok   func(error) bool
	}{
		"version 1 (no version line)":  {"[[package]]\n" + ownBlock("a", "0.1.0"), unsupportedCase(ReasonUnsupportedLockfile)},
		"version 2":                    {"version = 2\n\n[[package]]\n" + ownBlock("a", "0.1.0"), unsupportedCase(ReasonUnsupportedLockfile)},
		"version 5":                    {cargoLockText(5), unsupportedCase(ReasonUnsupportedLockfile)},
		"version as text":              {"version = \"4\"\n", unsupportedCase(ReasonUnsupportedLockfile)},
		"old metadata table":           {cargoLockText(4) + "\n[metadata]\n\"checksum a 1.0.0 (registry+x)\" = \"abc\"\n", unsupportedCase(ReasonUnsupportedLockfile)},
		"unused patch table":           {cargoLockText(4) + "\n[[patch.unused]]\nname = \"a\"\nversion = \"1.0.0\"\n", unsupportedCase(ReasonUnsupportedLockfile)},
		"unknown package key":          {cargoLockText(4, ownBlock("a", "0.1.0")+"extra = 1\n"), unsupportedCase(ReasonUnsupportedLockfile)},
		"git source":                   {cargoLockText(4, "name = \"g\"\nversion = \"1.0.0\"\nsource = \"git+https://github.com/x/g?rev=abc#abc\"\n"), unsupportedCase(ReasonUnsupportedSource)},
		"another registry":             {cargoLockText(4, "name = \"g\"\nversion = \"1.0.0\"\nsource = \"registry+https://example.com/index\"\nchecksum = \""+cksumA+"\"\n"), unsupportedCase(ReasonUnsupportedSource)},
		"sparse source":                {cargoLockText(4, "name = \"g\"\nversion = \"1.0.0\"\nsource = \"sparse+https://index.crates.io/\"\nchecksum = \""+cksumA+"\"\n"), unsupportedCase(ReasonUnsupportedSource)},
		"crates.io crate, no checksum": {cargoLockText(4, "name = \"g\"\nversion = \"1.0.0\"\nsource = \""+cratesIOSource+"\"\n"), plain},
		"checksum in capitals":         {cargoLockText(4, cratesBlock("g", "1.0.0", strings.Repeat("A", 64))), plain},
		"short checksum":               {cargoLockText(4, cratesBlock("g", "1.0.0", "abc")), plain},
		"member with a checksum":       {cargoLockText(4, "name = \"g\"\nversion = \"1.0.0\"\nchecksum = \""+cksumA+"\"\n"), plain},
		"same crate twice":             {cargoLockText(4, good, good), plain},
		"same name, same series":       {cargoLockText(4, good, cratesBlock("tokio", "1.20.0", cksumB)), plain},
		"same name, same 0.x series":   {cargoLockText(4, cratesBlock("t", "0.2.1", cksumA), cratesBlock("t", "0.2.9", cksumB)), plain},
		"bad version":                  {cargoLockText(4, cratesBlock("g", "1.0", cksumA)), plain},
		"bad name":                     {cargoLockText(4, cratesBlock("g h", "1.0.0", cksumA)), plain},
		"name is not a string":         {cargoLockText(4, "name = 3\nversion = \"1.0.0\"\n"), plain},
		"dependency not in the file":   {cargoLockText(4, ownBlock("a", "0.1.0", "ghost")), plain},
		"dependency version differs":   {cargoLockText(4, ownBlock("a", "0.1.0", "tokio 1.19.0"), good), plain},
		"dependency source differs":    {cargoLockText(4, ownBlock("a", "0.1.0", "tokio 1.18.0 (registry+https://example.com/index)"), good), plain},
		"dependency names two crates": {cargoLockText(4,
			ownBlock("a", "0.1.0", "t"), cratesBlock("t", "1.0.0", cksumA), cratesBlock("t", "2.0.0", cksumB)), plain},
		"two entries of one crate": {cargoLockText(4,
			ownBlock("a", "0.1.0", "t", "t 1.0.0"), cratesBlock("t", "1.0.0", cksumA)), plain},
		"dependency with four parts": {cargoLockText(4, ownBlock("a", "0.1.0", "t 1.0.0 (x) y"), cratesBlock("t", "1.0.0", cksumA)), plain},
		"dependency without parentheses": {cargoLockText(4,
			ownBlock("a", "0.1.0", "t 1.0.0 "+cratesIOSource), cratesBlock("t", "1.0.0", cksumA)), plain},
		"not TOML": {"version = 4\n[[package\n", plain},
	} {
		_, err := parseCargoLock([]byte(c.text))
		if err == nil || !c.ok(err) {
			t.Errorf("%s: err = %v", name, err)
		}
	}
	// A lock without packages is valid, and so is the same crate in two series.
	for name, text := range map[string]string{
		"no packages":                        cargoLockText(3),
		"two series":                         cargoLockText(4, cratesBlock("t", "1.0.0", cksumA), cratesBlock("t", "2.0.0", cksumB)),
		"a member and its name on crates.io": cargoLockText(4, ownBlock("t", "1.0.0"), cratesBlock("t", "1.0.0", cksumA)),
	} {
		if _, err := parseCargoLock([]byte(text)); err != nil {
			t.Errorf("%s: %v", name, err)
		}
	}
}
